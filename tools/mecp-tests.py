#!/usr/bin/env python3
"""mecp-tests.py <MECP checkout> > device-ui/tests/test_MecpCodec.cpp
Turns the specification's free-text conformance cases (freetext/tests.json) into a doctest file."""
import json, os, subprocess, sys

root = sys.argv[1]
cases = json.load(open(os.path.join(root, "freetext/tests.json"), encoding="utf-8"))
manifest = json.load(open(os.path.join(root, "freetext/manifest.json")))
assert manifest["schemaVersion"] == 1
commit = subprocess.run(["git", "-C", root, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()


def lit(text):
    out = ""
    for b in text.encode("utf-8"):
        if b in (0x22, 0x5C):
            out += "\\" + chr(b)
        elif 0x20 <= b < 0x7F:
            out += chr(b)
        else:
            out += "\\%03o" % b
    return '"' + out + '"'


print(f"""// Generated by kbview-harness/tools/mecp-tests.py from MECP {manifest['protocolVersion']} ({commit}),
// freetext/tests.json: {len(cases)} cases. Do not edit; run the script again after moving the pin.
#include "util/MecpCodec.h"
#include <cmath>
#include <doctest/doctest.h>

namespace
{{
struct Case {{
    const char *title;
    const char *input;
    bool valid;
    const char *time;      // "14:00" or nullptr
    long people;           // -1: none
    bool position;
    double latitude, longitude;
    const char *language, *callSign, *reference;
    long minutes;          // -1: none
}};

const Case c_cases[] = {{""")
for c in cases:
    e = c["expect"]
    valid = e is not None
    e = {k: v for k, v in (e or {}).items() if v is not None}
    unknown = set(e) - {"timestamp", "pax", "gps", "language", "callsign", "reference", "duration"}
    assert not unknown, unknown
    s = lambda k: lit(e[k]) if k in e else "nullptr"
    gps = e.get("gps")
    print("    {%s,\n     %s,\n     %s, %s, %s, %s, %s, %s, %s, %s, %s, %s}," % (
        lit(c["title"]), lit(c["input"]), "true" if valid else "false", s("timestamp"), e.get("pax", -1),
        "true" if gps else "false", repr(float(gps["lat"])) if gps else "0", repr(float(gps["lon"])) if gps else "0",
        s("language"), s("callsign"), s("reference"), e.get("duration", -1)))
print("""};
} // namespace

TEST_CASE("MecpCodec passes the specification's free-text cases")
{
    for (const Case &c : c_cases) {
        CAPTURE(c.title);
        mecp::Message m;
        const bool valid = mecp::decode(c.input, m);
        CHECK(valid == c.valid);
        if (!valid || !c.valid)
            continue;
        char time[8] = "";
        if (m.hasTime)
            snprintf(time, sizeof(time), "%02u:%02u", (unsigned)m.hour, (unsigned)m.minute);
        CHECK(std::string(time) == (c.time ? c.time : ""));
        CHECK((m.hasPeople ? (long)m.people : -1) == c.people);
        CHECK(m.hasPosition == c.position);
        if (m.hasPosition && c.position) {
            CHECK(std::fabs(m.latitude - c.latitude) < 1e-9);
            CHECK(std::fabs(m.longitude - c.longitude) < 1e-9);
        }
        CHECK(m.language == (c.language ? c.language : ""));
        CHECK(m.callSign == (c.callSign ? c.callSign : ""));
        CHECK(m.reference == (c.reference ? c.reference : ""));
        CHECK((m.hasDuration ? (long)m.minutes : -1) == c.minutes);
    }
}

TEST_CASE("MecpCodec reads the envelope")
{
    mecp::Message m;
    REQUIRE(mecp::decode("MECP/1/M01 P01 2pax 44.26010,-72.57540 @1432 road is out", m));
    CHECK(m.severity == mecp::Urgent);
    CHECK(m.codes == std::vector<std::string>{"M01", "P01"});
    CHECK(m.note == "road is out");
    CHECK_FALSE(m.drill);
    REQUIRE(mecp::decode("MECP/3/D01 Z99\\n", m));
    CHECK(m.drill);
    CHECK(m.codes.size() == 2);
    CHECK(mecp::phrase("Z99") == nullptr);
    CHECK(std::string(mecp::phrase("M01")) == "Injury");
    REQUIRE(mecp::decode("MECP/2/M01 P01  x", m)); // two spaces: the second "code" is free text
    CHECK(m.codes.size() == 1);
    CHECK(m.freetext == "P01  x");
    CHECK_FALSE(mecp::decode("MECP/4/M01", m));
    CHECK_FALSE(mecp::decode("MECP/1/m01", m));
    CHECK_FALSE(mecp::decode("MECP/1/M01 ", m));
    CHECK_FALSE(mecp::decode("mecp/1/M01", m));
    size_t count = 0;
    mecp::codeTable(count);
    CHECK(count == 109);
}

TEST_CASE("MecpCodec writes what it reads")
{
    mecp::Draft d;
    d.severity = mecp::Urgent;
    d.codes = {"M01", "R03"};
    d.people = 2;
    d.hasPosition = true;
    d.latitude = 44.2601;
    d.longitude = -72.5754;
    d.hasTime = true;
    d.hour = 14;
    d.minute = 32;
    d.callSign = "w1abc/p";
    d.reference = "Camp Two";
    d.minutes = 90;
    d.note = "bring  a\\nlitter";
    bool cut = true;
    const std::string line = mecp::encode(d, &cut);
    CHECK(line == "MECP/1/M01 R03 1h30min 2pax 44.26010,-72.57540 @1432 ~W1ABC/P #camp-two bring a litter");
    CHECK_FALSE(cut);
    mecp::Message m;
    REQUIRE(mecp::decode(line, m));
    CHECK(m.people == 2);
    CHECK(m.minutes == 90);
    CHECK(m.callSign == "W1ABC/P");
    CHECK(m.reference == "camp-two");
    CHECK(m.hour == 14);
    CHECK(m.note == "bring a litter");

    d.note = std::string(300, 'x') + "\\303\\251";
    const std::string longLine = mecp::encode(d, &cut);
    CHECK(cut);
    CHECK(longLine.size() <= mecp::c_maxBytes);
    CHECK(mecp::decode(longLine, m));
    d.codes.clear();
    CHECK(mecp::encode(d).empty());
    CHECK(mecp::durationText(2880) == "2d");
    CHECK(mecp::durationText(45) == "45min");
    CHECK(mecp::durationText(120) == "2h");
}""")
